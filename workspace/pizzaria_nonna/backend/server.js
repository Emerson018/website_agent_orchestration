import express from 'express';
import dotenv from 'dotenv';
import path from 'path';
import { fileURLToPath } from 'url';
import fs from 'fs';

import { setupSecurityGuardrails } from './security.js';
import { globalErrorHandler } from './errorHandler.js';
import { getDbClient } from './db.js';
import healthRouter from './routes/health.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

dotenv.config({ path: path.join(__dirname, '.env') });
dotenv.config();

const app = express();
const PORT = process.env.PORT || 5050;

// Body parser
app.use(express.json({ limit: '10mb' }));
app.use(express.urlencoded({ limit: '10mb', extended: true }));

// Setup Audited Security Guardrails (Helmet, CORS, Rate Limit)
setupSecurityGuardrails(app);

// Initialize DB Client
getDbClient();

// Mount standard health route
app.use('/api', healthRouter);

// Auto-mount dynamic business domain routes generated by AI
const routesDir = path.join(__dirname, 'routes');
if (fs.existsSync(routesDir)) {
  const routeFiles = fs.readdirSync(routesDir).filter((f) => f.endsWith('.js') && f !== 'health.js');
  for (const file of routeFiles) {
    const routeName = file.replace('.js', '');
    try {
      const modulePath = `./routes/${file}`;
      const routeModule = await import(modulePath);
      if (routeModule.default) {
        app.use(`/api/${routeName}`, routeModule.default);
        console.log(`[Composable Backend] Rota montada: /api/${routeName}`);
      }
    } catch (routeErr) {
      console.warn(`[Composable Backend] Falha ao carregar rota ${file}:`, routeErr.message);
    }
  }
}

// Global Error Handler
app.use(globalErrorHandler);

export const server = app.listen(PORT, () => {
  console.log(`[Composable Backend] Rodando com sucesso na porta ${PORT}`);
});

export default app;
